def _check_plaseval_input_files(sample_data_dict, binning, classification, merged_status):
    """ Check if PlasEval input files are present and not empty
    Input: 
    - sample_data_dict: dicionary generated by _read_samples_data
    - binning: (str in BINNING) binning method
    - classification: (str in CLASSIFICATION) classification method
    - merged_status: (str in MERGED_STATUS) meged status of experiment
    Output:
    - bool
    """
    files_to_check = [
        sample_data_dict[GFA],
        sample_data_dict[(binning,classification)],
        sample_data_dict[(PLASMERGE,binning,classification,merged_status)],
        sample_data_dict[(PLASEVAL,binning,classification,merged_status)],
        sample_data_dict[(PLASEVAL,GT,classification,UNMERGED)]
    ]
    input_correct = _check_files(
        files_to_check,
        in_msg=_prefix(sample_data_dict, binning, classification),
        exit_if_pbm=False
    )
    return input_correct

def _check_plaseval_output_files(sample_data_dict, binning, classification, merged_status, alpha):
    """ Check if PlasEval output files are present and not empty
    Input: 
    - sample_data_dict: dicionary generated by _read_samples_data
    - binning: (str in BINNING) binning method
    - classification: (str in CLASSIFICATION) classification method
    - merged_status: (str in MERGED_STATUS) meged status of experiment
    - alpha: (str) EVAL_CMD (eval mode) or alpha value (comp mode)
    Output:
    - bool
    """
    if alpha == EVAL_CMD:
        files_to_check = [
            sample_data_dict[(PLASEVAL,binning,classification,merged_status,EVAL_OUT)]
        ]
    else:
        files_to_check = [
            sample_data_dict[(PLASEVAL,binning,classification,merged_status,COMP_OUT,float(alpha))],
            sample_data_dict[(PLASEVAL,binning,classification,merged_status,COMP_LOG,float(alpha))]
        ]
    output_correct = _check_files(
        files_to_check,
        in_msg=_prefix(sample_data_dict, binning, classification),
        exit_if_pbm=False
    )
    return output_correct

def _write_plaseval_check_output_file(args, failed_experiments):
    """ Write te CSV file containing failed PlasEval experiments
    Input:
    - args: (argparse object) argument for the plaseval command
    - failed_experiments: list((int,str,str,str,str))
    sample index,binning method, classification method, meged_status, alpha
    where alpha s either the PlasEval comp mode alpha value, or INPUT_FILE or EVAL_CMD
    Output: None
    creates file args.output_file
    """
    with open(args.data_file) as in_file, open(args.output_file,"w") as out_file:
        in_lines = in_file.readlines()
        out_file.write(f"{in_lines[0].rstrip()},binning,classification,merged,alpha")
        for (sample_idx,binning,classification,merged,alpha) in failed_experiments:
            out_file.write(f"\n{in_lines[sample_idx].rstrip()},{binning},{classification},{merged},{alpha}")
    
def _check_plaseval_eval(args):
    """ Check PlasEval in eval mode input/output on a set of samples for all combinations (binning,classification,merged_status)
    Input:
    - args: (argparse object) argument for the CHECK_PLASMERGE command
    Output: None
    Creates a CSV file with all failed experiments, recording the combination (binning,classification,merged_status,alpha)
    where alpha is INPUT_FILE if an input file is missing, EVAL_CMD if the eval mode failed
    """
    samples_id_range = range(1,args.nb_samples+1)
    all_samples_data_dict = _read_samples_data(
        args.data_file, samples_id_range, args.alpha.split(","), args.output_dir
    )
    failed_experiments = []
    for (sample_idx,binning,classification,merged_status) in product(
            samples_id_range,
            args.binning.split(","),
            args.classification.split(","),
            args.merged_status.split(",")
    ):
        sample_data_dict = all_samples_data_dict[sample_idx]
        # Checking PlasEval input files
        input_correct = _check_plaseval_input_files(
            sample_data_dict, binning, classification, merged_status
        )
        if not input_correct:
            failed_experiments.append(
                (sample_idx,binning,classification,merged_status,INPUT_FILE)
            )        
        # Checking PlasEval eval output files
        eval_correct = _check_plaseval_output_files(
            sample_data_dict, binning, classification, merged_status, EVAL_CMD
        )       
        if input_correct and not eval_correct:
            failed_experiments.append(
                (sample_idx,binning,classification,merged_status,EVAL_CMD)
            )
    # Writing output file
    _write_plaseval_check_output_file(args, failed_experiments)

