class MissingFileError(Exception):
    """ Excepion raised when a file is missing """
    pass

class EmptyFileError(Exception):
    """ Excepion raised when a file is empty """
    pass

def _check_files(in_files, in_msg="", exit_if_pbm=True):
    """ Checking if a list of files is present and not empty
    Input:
    - in_files: list(str) list of file paths
    - in_msg: (str) message added to prints when errors
    - exit_if_pbm: (bool) if Tue, exist with 1 as son as a file is missing or empty
    Output: (if no exit)
    - bool: True if all files are present and none is empty
    Actions:
    prints a message for all checked files, with prefix #ERROR if file issing or empty
    """
    outcome = True
    for in_file in in_files:
        try:
            if not os.path.exists(in_file):
                raise MissingFileError(f"file {in_file} is missing")
            elif os.path.getsize(in_file) == 0:
                raise EmptyFileError(f"file {in_file} is empty")
            else:
                print(f"LOG: {in_msg} file {in_file} OK")
        except (MissingFileError, EmptyFileError) as e:
            print(f"ERROR: {in_msg} {e.args[0]}")
            if exit_if_pbm:
                sys.exit(1)
            else:
                outcome = False
    return outcome

def _sample_dir(sample_id, assembler, out_dir):
    return os.path.join(
        out_dir, f"{sample_id}_{assembler}"
    )

def _bins_file_path(
        sample_id, assembler,
        binning, classification,
        out_dir, merged, method
):
    """ Return the path of a generated plasmid bins file
    A bins file is either initial (present in the data file) or has been generated by a
    method (either PlasMege for merging) or PlasEval (conversion of a PlasMerge file)
    Input:
    - sample_id: (str) sample processed
    - assembler: (str) assembler used
    - binning: (str in BINNING) binning method used to generate the initial bins file
    - classifcation: (str in CLASSIFICATION) classification method used (ibid)
    - out_dir: (str) directory where to look for the file
    - merged: (str in MERGED): merged tatus of the bins
    - method: (str in [PLASMERGE,PLASEVAL]: method used to generate the processed file
    Output:
    - str: bins file path
    """
    return os.path.join(
        out_dir,
        f"{sample_id}_{assembler}.{binning}_{classification}.{method}.{merged}.tsv"
    )

def _merging_scores_file_path(
        sample_id, assembler,
        binning, classification,
        out_dir
):
    """ Returns the path to a bins meging score file generated by PlasMerge
    Input: see _bins_file_path
    - sample_id: (str) sample processed
    - assembler: (str) assembler used
    - binning: (str in BINNING) binning method used to generate the initial bins file
    - classifcation: (str in CLASSIFICATION) classification method used (ibid)
    - out_dir: (str) directory where to look for the file
    Output:
    - str: bins file path
    """
    return os.path.join(
        out_dir,
        f"{sample_id}_{assembler}.{binning}_{classification}.{PLASMERGE}.{SCORES_OUT}"
    )

def _plaseval_file_path(
        sample_id, assembler,
        binning, classification,
        out_dir,
        merged, alpha, suffix
):
    """ Returns the path of a file generated by PlasEval
    - sample_id: (str) sample processed
    - assembler: (str) assembler used
    - binning: (str in BINNING) binning method used to generate the initial bins file
    - classifcation: (str in CLASSIFICATION) classification method used (ibid)
    - out_dir: (str) directory where to look for the file
    - merged: (str in MERGED): merged tatus of the bins
    - alpha: (str either "" or  str(float)) alpha value used for PlasEval comp
      if "" => eval: the precision/recall/F1 file path is returned
    - suffix: (str in [EVAL_OUT,COMP_OUT,COMP_LOG]) returned file suffix
    Output:
    - str: PlasEval file path
    Use:
    To return the "eval" file: set alpha to "" and suffix=EVAL_OUT
    To return the "comp" log file, set alpha to its float value and suffix=COMP_LOG
    To return the "comp" out file, set alpha to its float value and suffix=COMP_OUT
    """
    if len(alpha) > 0:
        suffix2 = f"_{alpha}"
    else:
        suffix2 = ""
    return os.path.join(
        out_dir,
        f"{sample_id}_{assembler}.{binning}_{classification}.{merged}.{suffix}{suffix2}"
    )

""" Reading data
All data about processed samples are stored in a dictionary generated by _read_samples_data
index 1: sample index
index 2: sample information
SAMPLE: sample id
ASSEMBLER: assembler
GFA: gzipped GFA file
GC_PROBS: contigs GC pobabilities file
c in CLASSIFICATION: path to classification method c results file, in PlasBin-flow format

In all key below, b,c in BINNING x CLASSIFICATION
(b,c): initial plasmid bins file (in PlasEval format) obtained
       with binning (resp. classification) method b (resp c).
OUT_DIR: directory whee all results files for the sample are stored
(PLASMERGE,b,c,SCORES): merging scores file generated by PlasMerge for combination (b,c)
(PLASMERGE,b,c,UNMERGED): input (unmerged bins) file to PlasMerge for combination (b,c)
(PLASMERGE,b,c,MERGED): output (megred bis) file to PlasMerge for combination (b,c)
Both files above are in PlasMerge format.
(PLASEVAL,b,c,UNMERGED): input (unmerged bins) file to PlasMerge for combination (b,c)
(PLASEVAL,b,c,MERGED): output (megred bis) file to PlasMerge for combination (b,c)
Both files above are in PlasEval format, and b,c,m in BINNING x CLASSIFICATION x MERGED_STATUS
(PLASEVAL,b,c,m,EVAL_OUT): eval file generated by PlasEval for m bins and combination (b,c)
(PLASEVAL,b,c,m,COMP_LOG,a): comp log file generated by PlasEval for m bins and combination (b,c) and alpha=a
(PLASEVAL,b,c,m,COMP_OUT): comp out file generated by PlasEval for m bins and combination (b,c) and alpha=a

Keys below are used only to read a rerun data file recoding samples for which a PlasMerge experiment
did not succeed; only such files have the additional columns corresponding to these keys
BINNING_KEY in BINNING: binning method 
CLASSIFICATION_KEY in CLASSIFICATION: classification method

Keys below are used only to read a rerun data file recoding samples for which a PlasEval experiment
did not succeed; only such files have the additional columns corresponding to these keys
BINNING_KEY in BINNING: binning method 
CLASSIFICATION_KEY in CLASSIFICATION: classification method
MERGED_KEY: merged status
ALPHA_KEY: alpha value (or INPUT_FILE if an input file is missing or EVAL_CMD if eval failed)(
"""

def _read_samples_data(
        in_data_file, in_sample_idx,
        in_alpha,
        out_dir,
        rerun_plasmerge=False, rerun_plaseval=False
):
    """ Reading the samples data file and creating a dictionary recording all possible files paths
    Input:
    - in_data_file: (str) path to the samples data CSV fle
    - in_sample_idx: list(int) index in the file of the samples to read (1-base)
    - in_alpha: list(str): list of alpha values (considerign several values is used to check PlasEval results)
    - out_dir: (str) directory where are stored all experimetal results (one sub-directory per sample)
    - rerun_plasmerge: (bool) if True, read additional columns recording combinations for failed PlasMerge experiments
    - rerun_plaseval: (bool) ibid but for PlasEval
    Note: rerun_plasmerge and rerun_plaseval are used to read data for failed experiments to be redone, not the initial
    file
    Output:
    - dict(dict(k: str): dictionary used to access all informations about one or several samples
    index 1: samples
    index 2: keys to access sample information, see description above
    """
    _check_files([in_data_file])
    all_samples_data_dict = {}
    with open(in_data_file, newline='') as csvfile:
        data_lines = list(csv.DictReader(csvfile))        
        for sample_idx in in_sample_idx:
            sample_data = data_lines[sample_idx-1]
            sample_data_dict = {}
            # Reading data in CSV samples file
            sample_data_dict[SAMPLE] = sample_data[SAMPLE]
            sample_data_dict[ASSEMBLER] = sample_data[ASSEMBLER]
            sample_data_dict[GFA] = sample_data[GFA]
            sample_data_dict[GC_PROBS] = sample_data[GC_PROBS]
            for classification in CLASSIFICATION:
                sample_data_dict[classification] = sample_data[
                    f"input_pbf_{CLASSIFICATION_MAP[classification]}"
                ]
            for (binning,classification) in product(BINNING, CLASSIFICATION):
                if binning == MOB: sample_data_key = "mob_bins"
                elif binning == GT: sample_data_key = "gt_bins"
                else: sample_data_key = f"{BINNING_MAP[binning]}_{CLASSIFICATION_MAP[classification]}_bins"
                sample_data_dict[(binning,classification)] = sample_data[sample_data_key]            
            # Output directory
            sample_data_dict[OUT_DIR] = _sample_dir(
                sample_data_dict[SAMPLE], sample_data_dict[ASSEMBLER], out_dir
            )
            # PlasMerge files in PlasMerge format
            for (binning,classification) in product(BINNING, CLASSIFICATION):
                # Merging scores file
                key = (PLASMERGE,binning,classification,SCORES)
                sample_data_dict[key] =  _merging_scores_file_path(
                    sample_data_dict[SAMPLE], sample_data_dict[ASSEMBLER],
                    binning, classification, sample_data_dict[OUT_DIR]
                )
                # Bins files
                for merged in MERGED_STATUS:
                    key = (PLASMERGE,binning,classification,merged)
                    sample_data_dict[key] = _bins_file_path(
                        sample_data_dict[SAMPLE], sample_data_dict[ASSEMBLER],
                        binning, classification, sample_data_dict[OUT_DIR],
                        merged, PLASMERGE
                    )
            # PlasEval files in PlasEval format
            for (binning,classification,merged) in product(BINNING,CLASSIFICATION,MERGED_STATUS):
                key = (PLASEVAL,binning,classification,merged)
                # Bins files
                sample_data_dict[key] = _bins_file_path(
                sample_data_dict[SAMPLE], sample_data_dict[ASSEMBLER],
                    binning, classification, sample_data_dict[OUT_DIR],
                    merged, PLASEVAL
                )
                # Eval files
                key = (PLASEVAL,binning,classification,merged,EVAL_OUT)
                sample_data_dict[key] = _plaseval_file_path(
                    sample_data_dict[SAMPLE], sample_data_dict[ASSEMBLER],
                    binning, classification, sample_data_dict[OUT_DIR],
                    merged, "", EVAL_OUT
                )
                if len(in_alpha) > 0:
                    # Comp files
                    for (alpha,comp_suffix) in product(in_alpha,[COMP_OUT,COMP_LOG]):
                        key = (PLASEVAL,binning,classification,merged,comp_suffix,float(alpha))
                        sample_data_dict[key] = _plaseval_file_path(
                            sample_data_dict[SAMPLE], sample_data_dict[ASSEMBLER],
                            binning, classification, sample_data_dict[OUT_DIR],
                            merged, alpha, comp_suffix
                        )
            # Re-run information: classification, binning,alpha,merged status 
            if rerun_plasmerge or rerun_plaseval:
                sample_data_dict[BINNING_KEY] = sample_data[BINNING_KEY]
                sample_data_dict[CLASS_KEY] = sample_data[CLASS_KEY]
            if rerun_plaseval:
                sample_data_dict[ALPHA_KEY] = sample_data[ALPHA_KEY]
                sample_data_dict[MERGED_KEY] = sample_data[MERGED_KEY]
            all_samples_data_dict[sample_idx] = sample_data_dict
    return all_samples_data_dict

def _read_binning_classification(sample_data_dict, args):
    """ Returns a binning ethod and a classification method for a sample
    Input:
    - sample_data_dict: dicionary generated by _read_samples_data
    - args: (argparse object) argument for a command
    Output:
    - (str,str): name of a binning method and a classification method
    """
    if args.rerun:
        binning = sample_data_dict[BINNING_KEY]
        classification = sample_data_dict[CLASS_KEY]
    else:
        binning = args.binning
        classification = args.classification
    return binning,classification

def _read_merged_status(sample_data_dict, args):
    """ Returns a merged status
    Input:
    - sample_data_dict: dicionary generated by _read_samples_data
    - args: (argparse object) argument for a command
    Output:
    - (str) in MERGED_STATUS
    """
    if args.rerun:
        merged = sample_data_dict[MERGED_KEY]
    else:
        merged = args.merged_status
    return merged

def _read_alpha(sample_data_dict, args):
    """ Returns a alpha value used in a PlasEval experiment
    Input:
    - sample_data_dict: dicionary generated by _read_samples_data
    - args: (argparse object) argument for a command
    Output:
    - (str): alpha value
    """    
    if args.rerun:
        alpha = sample_data_dict[ALPHA_KEY]
    else:
        alpha = str(args.alpha)
    return alpha

def _prefix(sample_data_dict, binning, classification):
    """ Reurns the prefix of a file name
    Input:
    - sample_data_dict: dicionary generated by _read_samples_data
    - binning: (str in BINNING) binning method
    - classification: (str in CLASSIFICATION) classification method
    Output:
    - (str): file name prefix
    """
    return f"{sample_data_dict[SAMPLE]}_{sample_data_dict[ASSEMBLER]}.{binning}_{classification}"

